function escapeHtmlAttr(value: string | number): string {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * 解析图标名称或别名到 ICON_PATHS 的规范 key；若未提供名称则返回 null
 */
export function resolveIconKey(name?: string): string | null {
  if (!name) return null;
  const key = name.trim().toLowerCase();
  if (!key) return null;
  if (Object.prototype.hasOwnProperty.call(ICON_PATHS, key)) {
    return key;
  }
  const aliased = Object.prototype.hasOwnProperty.call(ICON_ALIASES, key)
    ? ICON_ALIASES[key]
    : undefined;
  if (aliased && Object.prototype.hasOwnProperty.call(ICON_PATHS, aliased)) {
    return aliased;
  }
  return 'sparkles';
}

export function renderIconSvg(
  name?: string,
  size = 24,
  strokeColor = 'currentColor',
  strokeWidth = 1.65
): string {
  const resolved = resolveIconKey(name);
  if (!resolved) return '';
  const inner = ICON_PATHS[resolved] || ICON_PATHS.sparkles;
  const safeResolved = escapeHtmlAttr(resolved);
  const safeColor = escapeHtmlAttr(strokeColor);
  const safeStroke = escapeHtmlAttr(strokeWidth);
  return `<svg class="vec-icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${safeColor}" stroke-width="${safeStroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" data-pptx-icon="${safeResolved}" data-icon-color="${safeColor}" data-icon-stroke="${safeStroke}">${inner}</svg>`;
}
